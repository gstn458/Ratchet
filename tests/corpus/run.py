#!/usr/bin/env python3
"""Run Ratchet over the pinned corpus and measure it against hand-made labels.

    python3 tests/corpus/run.py              # fetch, scan, write results, print summary
    python3 tests/corpus/run.py --check      # fail if results differ from the committed ones
    python3 tests/corpus/run.py --only age   # one repository

This is test tooling, not the scanner: it is the one place that makes network
calls (git fetches of the pinned commits). Checkouts are cached in
$RATCHET_CORPUS_DIR, by default ~/.cache/ratchet-corpus.

Files:
  manifest.json          repositories, each pinned to a commit
  results/<name>.json    what Ratchet found, committed, so any change in
                         detection shows up as a diff
  labels/<name>.json     hand verification: a verdict for each call site,
                         and the false negatives found by reading the code
  SUMMARY.md             the measurement, regenerated on every run

Precision is measured over call sites only. Imports are true by construction
(the import is there) and would flatter the number, so they are counted
separately and not labelled.
"""

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent
sys.path.insert(0, str(REPO_ROOT))

import ratchet  # noqa: E402

CACHE = Path(os.environ.get("RATCHET_CORPUS_DIR", Path.home() / ".cache" / "ratchet-corpus"))
VERDICTS = {"tp", "fp"}


def finding_key(f):
    return f"{f['path']}:{f['line']}:{f['label']}"


def checkout(repo):
    """The pinned commit of repo, fetched once and cached."""
    dest = CACHE / repo["name"]
    head = None
    if (dest / ".git").exists():
        head = subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"],
                              capture_output=True, text=True).stdout.strip()
    if head != repo["commit"]:
        dest.mkdir(parents=True, exist_ok=True)
        git = ["git", "-C", str(dest)]
        if not (dest / ".git").exists():
            subprocess.run(git + ["init", "-q"], check=True)
            subprocess.run(git + ["remote", "add", "origin", repo["url"]], check=True)
        subprocess.run(git + ["fetch", "-q", "--depth", "1", "origin", repo["commit"]], check=True)
        subprocess.run(git + ["checkout", "-q", "--detach", "FETCH_HEAD"], check=True)
    return dest


def scan(repo, path, backend="regex"):
    result = ratchet.walk(str(path), backend=backend)
    findings = sorted(
        ({"label": f.label, "algorithm": f.algorithm, "kind": f.kind, "test": f.in_test,
          "path": f.path.replace(os.sep, "/"), "line": f.line, "snippet": f.snippet}
         for f in result.findings),
        key=lambda f: (f["path"], f["line"], f["label"], f["kind"]),
    )
    return {
        "name": repo["name"],
        "commit": repo["commit"],
        "registry_version": ratchet.REGISTRY["registry_version"],
        "go_backend": result.parsers["Go"],
        "files_scanned": result.files,
        "unparsed": [f"{p} ({r})" for p, r in result.unparsed],
        "skipped_directories": len(result.skipped),
        "findings": findings,
    }


def comparable(result):
    """A result without the backend that produced it, for --check."""
    return {k: v for k, v in result.items() if k != "go_backend"}


def load_labels(name):
    path = HERE / "labels" / f"{name}.json"
    if not path.exists():
        return {"findings": {}, "missed": []}
    return json.loads(path.read_text())


def measure(result, labels):
    calls = [f for f in result["findings"] if f["kind"] == ratchet.CALL]
    imports = [f for f in result["findings"] if f["kind"] == ratchet.IMPORT]
    verdicts = [labels["findings"].get(finding_key(f), {}).get("verdict") for f in calls]
    return {
        "call_sites": len(calls),
        "in_test": sum(f["test"] for f in calls),
        "imports": len(imports),
        "labelled": sum(v in VERDICTS for v in verdicts),
        "tp": verdicts.count("tp"),
        "fp": verdicts.count("fp"),
        "missed": len(labels.get("missed", [])),
    }


def percent(part, whole):
    return f"{100 * part / whole:.1f}%" if whole else "n/a"


def summary(rows):
    lines = [
        "# Corpus measurement",
        "",
        "Generated by `tests/corpus/run.py`. Precision is over labelled call sites;",
        "imports are counted but not labelled. Missed findings are false negatives",
        "found by reading the code, listed in `labels/<name>.json`.",
        "",
        "| Repository | Language | Call sites | In test code | Imports | Labelled | False positives | FP rate | Missed |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    total = {k: 0 for k in ("call_sites", "in_test", "imports", "labelled", "tp", "fp", "missed")}
    for repo, m in rows:
        for k in total:
            total[k] += m[k]
        lines.append(f"| {repo['name']} | {repo['language']} | {m['call_sites']} | {m['in_test']} | {m['imports']} | "
                     f"{m['labelled']} | {m['fp']} | {percent(m['fp'], m['labelled'])} | {m['missed']} |")
    lines.append(f"| **total** | | {total['call_sites']} | {total['in_test']} | {total['imports']} | {total['labelled']} | "
                 f"{total['fp']} | {percent(total['fp'], total['labelled'])} | {total['missed']} |")
    lines += ["", f"Labelled {total['labelled']} of {total['call_sites']} call sites "
                  f"({percent(total['labelled'], total['call_sites'])})."]
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="exit 1 if results differ from the committed ones")
    p.add_argument("--only", action="append", help="limit to these repository names")
    p.add_argument("--backend", choices=ratchet.BACKENDS, default="regex",
                   help="Go backend (default regex, so committed results reproduce anywhere); "
                        "--check --backend tree-sitter checks the two backends agree")
    args = p.parse_args(argv)

    manifest = json.loads((HERE / "manifest.json").read_text())
    repos = [r for r in manifest["repositories"] if not args.only or r["name"] in args.only]
    rows, changed = [], []
    for repo in repos:
        print(f"{repo['name']} @ {repo['commit'][:12]}", file=sys.stderr)
        result = scan(repo, checkout(repo), args.backend)
        out = HERE / "results" / f"{repo['name']}.json"
        text = json.dumps(result, indent=2) + "\n"
        old = out.read_text() if out.exists() else None
        if old is None or comparable(json.loads(old)) != comparable(result):
            changed.append(repo["name"])
        if old != text and not args.check:
            out.write_text(text)
        rows.append((repo, measure(result, load_labels(repo["name"]))))

    report = summary(rows)
    print(report)
    if not args.only and not args.check:
        (HERE / "SUMMARY.md").write_text(report)
    if args.check and changed:
        print("results differ from the committed ones: " + ", ".join(changed), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
