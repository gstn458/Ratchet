#!/usr/bin/env python3
"""Copy registry.json into ratchet.py, so the single file runs on its own.

registry.json is the source of truth and the file that gets reviewed. ratchet.py
carries a verbatim copy between two marker lines, and uses it only when
registry.json is not sitting next to the script.

    python3 tools/embed_registry.py           # rewrite the embedded copy
    python3 tools/embed_registry.py --check   # exit 1 if it has drifted

tests/test_registry.py runs the check, so drift fails the build.
"""

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "registry.json")
SCRIPT = os.path.join(ROOT, "ratchet.py")

BEGIN = "# BEGIN EMBEDDED REGISTRY: generated by tools/embed_registry.py from registry.json. Do not edit.\n"
END = "# END EMBEDDED REGISTRY\n"


def render(registry_text):
    # Raw triple-single-quoted literal: JSON never needs ''' and never ends in
    # a backslash, but refuse rather than emit a literal that changes meaning.
    if "'''" in registry_text or registry_text.rstrip("\n").endswith("\\"):
        raise ValueError("registry.json cannot be embedded as a raw string literal")
    return BEGIN + "_EMBEDDED_REGISTRY = r'''" + registry_text + "'''\n" + END


def embedded(script_text, registry_text):
    """Return script_text with the block between the markers replaced."""
    start = script_text.index(BEGIN)
    end = script_text.index(END, start) + len(END)
    return script_text[:start] + render(registry_text) + script_text[end:]


def read(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read()


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="exit 1 if ratchet.py is out of date")
    args = p.parse_args(argv)

    script, registry = read(SCRIPT), read(REGISTRY)
    updated = embedded(script, registry)
    if args.check:
        if updated != script:
            print("ratchet.py's embedded registry differs from registry.json. "
                  "Run: python3 tools/embed_registry.py", file=sys.stderr)
            return 1
        return 0
    if updated != script:
        with open(SCRIPT, "w", encoding="utf-8", newline="") as fh:
            fh.write(updated)
        print("updated the embedded registry in ratchet.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
