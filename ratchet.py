def build_cbom(scan, root, tool_version=VERSION):
    grouped = defaultdict(list)
    for f in scan.findings:
        grouped[f.label].append(f)

    components = []
    for label, group in sorted(grouped.items()):
        group = sorted(group, key=lambda f: (f.path, f.line))
        algo = group[0].algorithm
        spec = ALGORITHMS[algo]
        params = group[0].params
        oid, level = parameter_claims(algo, params)
        crypto_properties = {
            "assetType": "algorithm",
            "algorithmProperties": {
                "primitive": spec["primitive"],
                "parameterSetIdentifier": str(params) if params else "unspecified",
                "executionEnvironment": "software-plain-ram",
                "implementationPlatform": "generic",
                "certificationLevel": ["none"],
                "cryptoFunctions": sorted(spec["functions"]),
                "nistQuantumSecurityLevel": level,
            },
        }
        if oid is not None:
            crypto_properties["oid"] = oid
        components.append({
            "type": "cryptographic-asset",
            "bom-ref": f"crypto/algorithm/{label.lower()}",
            "name": label,
            "cryptoProperties": crypto_properties,
            "evidence": {
                "occurrences": [
                    {"location": f"{f.path}#L{f.line}", "additionalContext": f.kind}
                    for f in group[:50]
                ]
            },
            "properties": sorted([
                {"name": "ratchet:quantum_status", "value": spec["quantum"]},
                {"name": "ratchet:classical_status", "value": spec["classical"]},
                {"name": "ratchet:rationale", "value": spec["why"]},
                {"name": "ratchet:recommended_replacement", "value": spec["replacement"]},
                {"name": "ratchet:occurrence_count", "value": str(len(group))},
                {"name": "ratchet:call_site_count",
                 "value": str(sum(f.kind == CALL for f in group))},
                {"name": "ratchet:import_count",
                 "value": str(sum(f.kind == IMPORT for f in group))},
            ], key=lambda p: p["name"]),
        })

    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "serialNumber": f"urn:uuid:{uuid.uuid4()}",
        "version": 1,
        "metadata": {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "tools": {
                "components": [{
                    "type": "application",
                    "name": "ratchet",
                    "version": tool_version,
                }]
            },
            "component": {
                "type": "application",
                "bom-ref": "target",
                "name": os.path.basename(os.path.abspath(root)) or "target",
            },
            # CycloneDX metadata admits no custom fields, so the registry that
            # produced this CBOM is recorded as namespaced properties.
            # What was not scanned is part of what the document claims, so
            # every skipped directory is listed (property names may repeat).
            "properties": sorted([
                {"name": "ratchet:scan_registry_version", "value": REGISTRY["registry_version"]},
                {"name": "ratchet:scan_registry_sha256", "value": REGISTRY_DIGEST},
                {"name": "ratchet:include_vendored", "value": str(scan.include_vendored).lower()},
                {"name": "ratchet:skipped_directory_count", "value": str(len(scan.skipped))},
            ] + [
                {"name": "ratchet:skipped_directory", "value": f"{path} ({reason})"}
                for path, reason in scan.skipped
            ], key=lambda p: (p["name"], p["value"])),
        },
        "components": components,
    }


