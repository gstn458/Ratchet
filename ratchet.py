IMPORT, CALL, NAME = "import", "call site", "algorithm name"


class Finding:
    """One occurrence of an algorithm. kind is IMPORT for an import line, which
    shows a library is present but not that it is used, or CALL otherwise."""

    def __init__(self, algorithm, path, line, snippet, params=None, kind=CALL):
        self.algorithm = algorithm
        self.path = path
        self.line = line
        self.snippet = snippet.strip()[:160]
        self.params = params
        self.kind = kind
        self.suppressed_by = None  # the SuppressRule that matched, if any
        self.in_test = False       # set by walk() from the file's path

    @property
    def context(self):
        """CycloneDX additionalContext for this occurrence."""
        return f"{self.kind} (test code)" if self.in_test else self.kind

    @property
    def label(self):
        return f"{self.algorithm}-{self.params}" if self.params else self.algorithm


def add_names(findings, path, lines, named):
    """Append algorithm-name findings for [(line, value, names)], one per line
    and algorithm, skipping any a call site on the same line already counts."""
    seen = {(f.line, f.algorithm) for f in findings if f.kind == CALL}
    for line, names in named:
        for algo, params in names:
            if (line, algo) not in seen:
                seen.add((line, algo))
                snippet = lines[line - 1] if 0 < line <= len(lines) else ""
                findings.append(Finding(algo, path, line, snippet, params, kind=NAME))


