def build_cbom(scan, root, tool_version=VERSION):
    # Suppressed occurrences form their own component per rule, so the
    # vulnerability analysis attached to it covers only what the rule matched.
    grouped = defaultdict(list)
    for f in scan.findings:
        grouped[(f.label, f.suppressed_by.line if f.suppressed_by else 0)].append(f)

    components, vulnerabilities = [], []
    for (label, rule_line), group in sorted(grouped.items()):
        group = sorted(group, key=lambda f: (f.path, f.line))
        rule = group[0].suppressed_by
        algo = group[0].algorithm
        spec = ALGORITHMS[algo]
        params = group[0].params
        oid, level = parameter_claims(algo, params)
        crypto_properties = {
            "assetType": "algorithm",
            "algorithmProperties": {
                "primitive": spec["primitive"],
                "parameterSetIdentifier": str(params) if params else "unspecified",
                "executionEnvironment": "software-plain-ram",
                "implementationPlatform": "generic",
                "certificationLevel": ["none"],
                "cryptoFunctions": sorted(spec["functions"]),
                "nistQuantumSecurityLevel": level,
            },
        }
        if oid is not None:
            crypto_properties["oid"] = oid
        ref = f"crypto/algorithm/{label.lower()}"
        suppression = []
        if rule:
            ref += f"/suppressed/line-{rule.line}"
            suppression = [
                {"name": "ratchet:suppressed_by", "value": f"{rule.text} ({IGNORE_FILE} line {rule.line})"},
                {"name": "ratchet:suppression_reason", "value": rule.reason},
                {"name": "ratchet:suppression_state", "value": rule.state},
            ]
            vulnerabilities.append({
                "bom-ref": f"vulnerability/{label.lower()}/suppressed/line-{rule.line}",
                "id": vulnerability_id(algo),
                "source": {"name": "Ratchet"},
                "description": spec["why"],
                "recommendation": spec["replacement"],
                "analysis": {"state": rule.state, "detail": rule.reason},
                "affects": [{"ref": ref}],
                "properties": [{"name": "ratchet:suppression_rule",
                                "value": f"{rule.text} ({IGNORE_FILE} line {rule.line})"}],
            })
        components.append({
            "type": "cryptographic-asset",
            "bom-ref": ref,
            "name": label,
            "cryptoProperties": crypto_properties,
            "evidence": {
                "occurrences": [
                    {"location": f"{f.path}#L{f.line}", "additionalContext": f.context}
                    for f in group
                ]
            },
            "properties": sorted([
                {"name": "ratchet:quantum_status", "value": spec["quantum"]},
                {"name": "ratchet:classical_status", "value": spec["classical"]},
                {"name": "ratchet:rationale", "value": spec["why"]},
                {"name": "ratchet:recommended_replacement", "value": spec["replacement"]},
                {"name": "ratchet:occurrence_count", "value": str(len(group))},
                {"name": "ratchet:call_site_count",
                 "value": str(sum(f.kind == CALL for f in group))},
                {"name": "ratchet:import_count",
                 "value": str(sum(f.kind == IMPORT for f in group))},
            ] + suppression, key=lambda p: p["name"]),
        })

    cbom = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "serialNumber": f"urn:uuid:{uuid.uuid4()}",
        "version": 1,
        "metadata": {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "tools": {
                "components": [{
                    "type": "application",
                    "name": "ratchet",
                    "version": tool_version,
                }]
            },
            "component": {
                "type": "application",
                "bom-ref": "target",
                "name": os.path.basename(os.path.abspath(root)) or "target",
            },
            # CycloneDX metadata admits no custom fields, so the registry that
            # produced this CBOM is recorded as namespaced properties.
            # What was not scanned is part of what the document claims, so
            # every skipped directory is listed (property names may repeat).
            "properties": sorted([
                {"name": "ratchet:scan_registry_version", "value": REGISTRY["registry_version"]},
                {"name": "ratchet:scan_registry_sha256", "value": REGISTRY_DIGEST},
                {"name": "ratchet:include_vendored", "value": str(scan.include_vendored).lower()},
            ] + [
                {"name": "ratchet:parser", "value": f"{language}: {parser}"}
                for language, parser in scan.parsers.items()
            ] + [
                {"name": "ratchet:skipped_directory_count", "value": str(len(scan.skipped))},
                {"name": "ratchet:unparsed_file_count", "value": str(len(scan.unparsed))},
                {"name": "ratchet:not_scanned_file_count",
                 "value": str(sum(len(paths) for paths in scan.not_scanned.values()))},
            ] + [
                {"name": "ratchet:not_scanned_file",
                 "value": f"{path} ({language}: {not_scanned_reason(scan, language)})"}
                for language, paths in scan.not_scanned.items() for path in paths
            ] + [
                {"name": "ratchet:ignored_file_count",
                 "value": str(sum(len(r.matched) for r in scan.ignore_rules or ()))},
                {"name": "ratchet:suppressed_finding_count",
                 "value": str(sum(f.suppressed_by is not None for f in scan.findings))},
            ] + [
                {"name": "ratchet:suppression_rule",
                 "value": f"{r.text} -- {r.reason} ({IGNORE_FILE} line {r.line}, "
                          f"{plural(len(r.matched), 'finding')})"}
                for r in scan.suppress_rules or ()
            ] + [
                {"name": "ratchet:ignore_rule",
                 "value": f"{r.pattern} -- {r.reason} ({IGNORE_FILE} line {r.line}, "
                          f"{plural(len(r.matched), 'file')})"}
                for r in scan.ignore_rules or ()
            ] + [
                {"name": "ratchet:ignored_file", "value": f"{path} ({r.pattern})"}
                for r in scan.ignore_rules or () for path in r.matched
            ] + [
                {"name": "ratchet:skipped_directory", "value": f"{path} ({reason})"}
                for path, reason in scan.skipped
            ] + [
                {"name": "ratchet:unparsed_file", "value": f"{path} ({reason})"}
                for path, reason in scan.unparsed
            ], key=lambda p: (p["name"], p["value"])),
        },
        "components": components,
    }
    if vulnerabilities:
        cbom["vulnerabilities"] = sorted(vulnerabilities, key=lambda v: v["bom-ref"])
    return cbom


