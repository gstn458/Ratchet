class PyVisitor(ast.NodeVisitor):
    def __init__(self, path, source_lines):
        self.path = path
        self.lines = source_lines
        self.findings = []
        self.aliases = {}   # local name -> algorithm
        self.imported = {}  # local name -> (module, imported name or None)
        # Elliptic-curve usage, resolved in resolve_ec once the file is read.
        self.ec_keys = defaultdict(list)  # binding -> keygen findings
        self.ec_derived = {}              # binding -> binding it derives from
        self.ec_uses = []                 # (binding, usage)
        self.ec_markers = set()           # usages proven by usage objects
        self._keygen = {}                 # id(call node) -> keygen finding

    def _line(self, node):
        idx = node.lineno - 1
        return self.lines[idx] if 0 <= idx < len(self.lines) else ""

    def _add(self, algo, node, params=None):
        finding = Finding(algo, self.path, node.lineno, self._line(node), params)
        self.findings.append(finding)
        return finding

    def _qualified(self, expr):
        """Fully qualified dotted name an expression refers to through this
        file's imports, or None: ec.ECDH and a from-imported ECDH both give
        cryptography.hazmat.primitives.asymmetric.ec.ECDH."""
        if isinstance(expr, ast.Name) and expr.id in self.imported:
            module, name = self.imported[expr.id]
            return f"{module}.{name}" if name else module
        if isinstance(expr, ast.Attribute):
            base = self._qualified(expr.value)
            return f"{base}.{expr.attr}" if base else None
        return None

    def _key_arguments(self, node):
        """Bindings of every argument and keyword value of a call."""
        values = list(node.args) + [kw.value for kw in node.keywords]
        return [b for b in (self._binding(v) for v in values) if b]

    @staticmethod
    def _binding(expr):
        """A stable text name for the object an expression refers to, with
        derivations such as .public_key() stripped, or None."""
        while (isinstance(expr, ast.Call) and not expr.args and not expr.keywords
               and isinstance(expr.func, ast.Attribute)
               and expr.func.attr in PY_EC_DERIVE_METHODS):
            expr = expr.func.value
        if isinstance(expr, (ast.Name, ast.Attribute)):
            return ast.unparse(expr)
        return None

    def visit_Assign(self, node):
        self.generic_visit(node)
        value = node.value
        stripped = value
        while (isinstance(stripped, ast.Call) and isinstance(stripped.func, ast.Attribute)
               and stripped.func.attr in PY_EC_DERIVE_METHODS):
            stripped = stripped.func.value
        keygen = self._keygen.get(id(stripped))
        source = None if keygen else self._binding(value)
        for target in node.targets:
            if not isinstance(target, (ast.Name, ast.Attribute)):
                continue
            name = ast.unparse(target)
            if keygen:
                self.ec_keys[name].append(keygen)
            elif source and source != name:
                self.ec_derived[name] = source

    def resolve_ec(self):
        """Relabel EC findings as ECDSA or ECDH where the usage is visible.

        A generated key takes the usage of the name it is bound to, following
        derivations such as public_key(). A key that cannot be followed, and
        the import line, take the file's usage only when every usage seen in
        the file agrees. Anything else stays EC, usage undetermined.
        """
        def root(name):
            seen = set()
            while name in self.ec_derived and name not in seen:
                seen.add(name)
                name = self.ec_derived[name]
            return name

        usage = defaultdict(set)
        for name, kind in self.ec_uses:
            usage[root(name)].add(kind)

        resolved = set()
        file_kinds = set(self.ec_markers)
        for name, keygens in self.ec_keys.items():
            kinds = usage.get(root(name), set())
            file_kinds |= kinds
            if len(kinds) == 1:
                for f in keygens:
                    f.algorithm = next(iter(kinds))
                    resolved.add(id(f))

        if len(file_kinds) == 1:
            only = next(iter(file_kinds))
            for f in self.findings:
                if f.algorithm == "EC" and id(f) not in resolved:
                    f.algorithm = only

    def visit_Import(self, node):
        for alias in node.names:
            local = alias.asname or alias.name.split(".")[0]
            self.imported[local] = (alias.name if alias.asname else local, None)
            algo = PY_MODULES.get(alias.name)
            if algo:
                self.aliases[local] = algo
                self._add(algo, node)
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        if not node.module:
            return self.generic_visit(node)
        for alias in node.names:
            full = f"{node.module}.{alias.name}"
            local = alias.asname or alias.name
            self.imported[local] = (node.module, alias.name)
            algo = PY_MODULES.get(full) or PY_MODULES.get(node.module)
            if algo:
                self.aliases[local] = algo
                self._add(algo, node)
        self.generic_visit(node)

    def visit_Call(self, node):
        func = node.func
        name = getattr(func, "attr", None) or getattr(func, "id", None)
        owner = None
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
            owner = func.value.id

        # Elliptic-curve usage: ec.ECDSA(...) and ec.ECDH() are call sites with
        # a known usage; .sign(), .verify() and .exchange() say what a key is for.
        qualified = self._qualified(func)
        usage_object = PY_EC_USAGE_OBJECTS.get(qualified)
        usage_function = PY_EC_USAGE_FUNCTIONS.get(qualified)
        for kind in filter(None, (usage_object, usage_function)):
            for key in self._key_arguments(node):
                self.ec_uses.append((key, kind))
        if isinstance(func, ast.Attribute) and func.attr in PY_EC_USAGE_METHODS:
            kind = PY_EC_USAGE_METHODS[func.attr]
            receiver = self._binding(func.value)
            if receiver:
                self.ec_uses.append((receiver, kind))
            # The peer key passed to exchange() is a key-agreement key too.
            if kind == "ECDH":
                for arg in node.args:
                    peer = self._binding(arg)
                    if peer:
                        self.ec_uses.append((peer, kind))

        if usage_object:
            self.ec_markers.add(usage_object)
            self._add(usage_object, node)

        # hashlib.md5(), hashlib.sha1()
        elif name in ("md5", "sha1"):
            self._add(PY_HASH_NAMES[name], node)

        # hashlib.new("md5")
        elif name == "new" and node.args:
            first = node.args[0]
            if isinstance(first, ast.Constant) and isinstance(first.value, str):
                algo = PY_HASH_NAMES.get(first.value.lower())
                if algo:
                    self._add(algo, node)

        # rsa.generate_private_key(key_size=2048)
        elif name in ("generate_private_key", "generate_parameters", "generate"):
            algo = self.aliases.get(owner)
            if algo:
                params = None
                for kw in node.keywords:
                    if kw.arg in ("key_size", "bits") and isinstance(kw.value, ast.Constant):
                        params = str(kw.value.value)
                if params is None and node.args:
                    a = node.args[0]
                    if isinstance(a, ast.Constant) and isinstance(a.value, int):
                        params = str(a.value)
                    elif isinstance(a, ast.Call):
                        curve = getattr(a.func, "attr", None) or getattr(a.func, "id", None)
                        if curve:
                            params = curve
                finding = self._add(algo, node, params)
                if algo == "EC":
                    self._keygen[id(node)] = finding

        self.generic_visit(node)


def scan_python(path):
    try:
        source = open(path, "r", encoding="utf-8", errors="replace").read()
        tree = ast.parse(source, filename=path)
    except (SyntaxError, ValueError, OSError):
        return []
    visitor = PyVisitor(path, source.splitlines())
    visitor.visit(tree)
    visitor.resolve_ec()
    return visitor.findings


# ---------------------------------------------------------------------------
# Go scanning via text patterns
# ---------------------------------------------------------------------------

def go_lex(text):
    """Split Go source into code and string literals, line by line.

    Returns (code, strings): code[i] is line i with comments removed and every
    string or rune literal reduced to its empty quotes, and strings[i] lists
    the contents of the string literals that start on line i. This is not a Go
    parser. It is just enough to tell code from comments and strings, so
    nothing inside either is mistaken for an import or a call.
    """
    code, strings = [], []
    line_code, line_strings = [], []
    i, n = 0, len(text)
    state = None  # None, "block" (/* */) or "raw" (`...`)
    raw, raw_line = [], 0

    def end_line():
        code.append("".join(line_code))
        strings.append(line_strings[:])
        line_code.clear()
        line_strings.clear()

    while i < n:
        c = text[i]
        if c == "\n":
            if state == "raw":
                raw.append(c)
            end_line()
            i += 1
        elif state == "block":
            if text.startswith("*/", i):
                state = None
                line_code.append(" ")
                i += 2
            else:
                i += 1
        elif state == "raw":
            if c == "`":
                state = None
                line_code.append("``")
                # Attributed to the line the literal opens on.
                if raw_line == len(code):
                    line_strings.append("".join(raw))
                else:
                    strings[raw_line].append("".join(raw))
                i += 1
            else:
                raw.append(c)
                i += 1
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            state = "block"
            i += 2
        elif c == "`":
            state = "raw"
            raw, raw_line = [], len(code)
            i += 1
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            if c == '"':
                line_strings.append(text[i + 1:j])
            line_code.append(c + c)
            i = j + 1
        else:
            line_code.append(c)
            i += 1
    end_line()
    return code, strings


GO_IMPORT_LINE = re.compile(r"^\s*import\b")


def go_imports(code, strings):
    """{line index: [import paths]} for import declarations only."""
    imports = {}
    in_group = False
    for idx, line in enumerate(code):
        if in_group:
            imports[idx] = strings[idx]
            if ")" in line:
                in_group = False
        elif GO_IMPORT_LINE.match(line):
            imports[idx] = strings[idx]
            after = line.split("import", 1)[1]
            if after.lstrip().startswith("(") and ")" not in after:
                in_group = True
    return {k: v for k, v in imports.items() if v}


def scan_go(path):
    findings = []
    try:
        lines = open(path, "r", encoding="utf-8", errors="replace").read().splitlines()
    except OSError:
        return []

    code, strings = go_lex("\n".join(lines))
    import_lines = go_imports(code, strings)
    imports = {p for paths in import_lines.values() for p in paths}

    import_findings = defaultdict(list)  # import path -> its findings
    for idx, paths in sorted(import_lines.items()):
        for import_path in paths:
            algo = GO_IMPORTS.get(import_path)
            if algo:
                findings.append(Finding(algo, path, idx + 1, lines[idx]))
                import_findings[import_path].append(findings[-1])
    variants = defaultdict(set)  # import path -> algorithms its calls used
    # Patterns run on code only, so calls in comments and strings never match.
    # The finding still shows the original line.
    for i, (line, text) in enumerate(zip(lines, code), start=1):
        for pattern, algo, group in GO_CALL_PATTERNS:
            m = pattern.search(text)
            if m:
                params = m.group(group) if group else None
                findings.append(Finding(algo, path, i, line, params))
        for import_path, patterns in GO_VARIANT_CALLS.items():
            for pattern, algo in patterns:
                if pattern.search(text):
                    variants[import_path].add(algo)
                    findings.append(Finding(algo, path, i, line))
        if GO_ELLIPTIC_IMPORT in imports and any(p.search(text) for p in GO_ELLIPTIC_DIRECT):
            findings.append(Finding("EC", path, i, line))

    for import_path, used in variants.items():
        if len(used) == 1:
            for f in import_findings[import_path]:
                f.algorithm = next(iter(used))
    return findings


# ---------------------------------------------------------------------------
# Walk
# ---------------------------------------------------------------------------

def walk(root):
    findings = []
    files = 0
    for dirpath, dirnames, filenames in os.walk(root):
        # Sorted so the scan order, and everything derived from it, does not
        # depend on the filesystem's directory ordering.
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root)
            if fn.endswith(".py"):
                files += 1
                for f in scan_python(full):
                    f.path = rel
                    findings.append(f)
            elif fn.endswith(".go"):
                files += 1
                for f in scan_go(full):
                    f.path = rel
                    findings.append(f)
    return findings, files


