IMPORT, CALL = "import", "call site"


class Finding:
    """One occurrence of an algorithm. kind is IMPORT for an import line, which
    shows a library is present but not that it is used, or CALL otherwise."""

    def __init__(self, algorithm, path, line, snippet, params=None, kind=CALL):
        self.algorithm = algorithm
        self.path = path
        self.line = line
        self.snippet = snippet.strip()[:160]
        self.params = params
        self.kind = kind
        self.suppressed_by = None  # the SuppressRule that matched, if any
        self.in_test = False       # set by walk() from the file's path

    @property
    def context(self):
        """CycloneDX additionalContext for this occurrence."""
        return f"{self.kind} (test code)" if self.in_test else self.kind

    @property
    def label(self):
        return f"{self.algorithm}-{self.params}" if self.params else self.algorithm


