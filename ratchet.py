# JCA engine classes whose getInstance(name) names the algorithm.
JCA_CLASSES = {
    "KeyPairGenerator", "KeyFactory", "Signature", "Cipher", "KeyAgreement", "MessageDigest",
    "Mac", "KeyGenerator", "SecretKeyFactory", "AlgorithmParameterGenerator", "AlgorithmParameters",
}

# Standard JCA names (Java Security Standard Algorithm Names), lower-cased, as
# JCA matches them without regard to case. Only algorithms in the registry
# are mapped; anything else (SHA-384, SHA-512, SHA-3) records nothing.
JCA_NAMES = {
    "rsa": "RSA", "rsassa-pss": "RSA",
    "ec": "EC", "ecdsa": "ECDSA", "ecdh": "ECDH", "ecdhc": "ECDH",
    "dsa": "DSA", "dh": "DH", "diffiehellman": "DH",
    "ed25519": "Ed25519", "x25519": "X25519", "ed448": "Ed448", "x448": "X448",
    "eddsa": "EdDSA", "xdh": "XDH",
    "des": "DES", "desede": "3DES", "tripledes": "3DES",
    "rc4": "RC4", "arcfour": "RC4", "aes": "AES",
    "md5": "MD5", "sha1": "SHA-1", "sha-1": "SHA-1", "sha": "SHA-1",
    "sha256": "SHA-256", "sha-256": "SHA-256",
}
# Inside a compound name the hash is spelled in full (HmacSHA1, SHA1withRSA);
# bare "SHA" is SHA-1's alias only as a MessageDigest name, and "HmacSHA" is
# the start of a name built at run time ("HmacSHA" + bits), not SHA-1.
JCA_COMPOUND_HASHES = {k: v for k, v in JCA_NAMES.items() if k != "sha"}
JCA_SIGNATURE = re.compile(r"(?P<hash>[a-z0-9/-]+?)with(?P<key>rsa|ecdsa|dsa)(?:andmgf1|/pss|inp1363format)?")
JCA_PREFIXED = re.compile(r"(?:hmac|pbkdf2withhmac)(?P<hash>.+)")
JCA_PBE = re.compile(r"pbewith(?P<hash>[a-z0-9-]+?)and(?P<cipher>.+)")
JCA_OAEP = re.compile(r"oaepwith(?P<hash>.+?)andmgf1padding")


# Where a key generator takes its parameter set: KeyPairGenerator.initialize
# and KeyGenerator.init, with a size or a parameter spec.
JCA_INIT_METHODS = {"KeyPairGenerator": "initialize", "KeyGenerator": "init"}
JCA_SIZE_ALGORITHMS = {"RSA", "DSA", "DH", "AES"}  # whose parameter set is a key size


# Named curves in JCA (ECGenParameterSpec, JWK "crv" lookups), recorded as EC
# with the curve as the parameter set, named as Python's cryptography names it.
JCA_CURVES = {"secp256r1": "SECP256R1", "prime256v1": "SECP256R1", "secp384r1": "SECP384R1",
              "secp521r1": "SECP521R1", "secp256k1": "SECP256K1", "secp224r1": "SECP224R1"}

# Names that say which algorithm they are wherever they appear. Short names
# ("RSA", "EC", "MD5", "SHA-1", "DES") are used as labels too often to claim
# anything outside getInstance.
JCA_UNAMBIGUOUS = {"rsassa-pss", "desede", "tripledes", "diffiehellman", "ecdh", "ecdsa",
                   "ed25519", "x25519", "ed448", "x448", "eddsa", "xdh", "arcfour"}
JCA_TRANSFORMATION = re.compile(r"[a-z0-9_-]+/[a-z0-9]+/[a-z0-9-]*padding")


def jca_named(name):
    """[(algorithm, parameter set or None)] for a string literal that is an
    unambiguous JCA algorithm or curve name, else []."""
    n = name.lower()
    if n in JCA_CURVES:
        return [("EC", JCA_CURVES[n])]
    if (n in JCA_UNAMBIGUOUS or JCA_SIGNATURE.fullmatch(n) or JCA_TRANSFORMATION.fullmatch(n)
            or JCA_PBE.fullmatch(n) or JCA_PREFIXED.fullmatch(n)):
        return [(algo, None) for algo in jca_algorithms(name)]
    return []


def jca_name(name):
    """A name with a key or block size suffix (AES_256, RC4_128) removed."""
    return re.sub(r"_\d+$", "", name)


def jca_algorithms(name):
    """The registry algorithms a JCA algorithm name uses, one per primitive:
    SHA1withRSA is RSA and SHA-1, RSA/ECB/OAEPWithSHA-1AndMGF1Padding is RSA
    and SHA-1, PBEWithMD5AndDES is MD5 and DES. [] for a name it does not know."""
    n = name.strip().lower()
    m = JCA_SIGNATURE.fullmatch(n)
    if m:
        key = JCA_NAMES[m.group("key")]
        digest = JCA_COMPOUND_HASHES.get(m.group("hash"))
        return [key] + ([digest] if digest else [])
    if "/" in n:  # Cipher transformation: algorithm/mode/padding
        cipher, _, rest = n.partition("/")
        found = [JCA_NAMES[jca_name(cipher)]] if jca_name(cipher) in JCA_NAMES else []
        oaep = JCA_OAEP.search(rest)
        if oaep and JCA_COMPOUND_HASHES.get(oaep.group("hash")):
            found.append(JCA_COMPOUND_HASHES[oaep.group("hash")])
        return found
    m = JCA_PBE.fullmatch(n)
    if m:
        digest = JCA_COMPOUND_HASHES.get(re.sub(r"^hmac", "", m.group("hash")))
        cipher = JCA_NAMES.get(jca_name(m.group("cipher")))
        return [x for x in (digest, cipher) if x]
    m = JCA_PREFIXED.fullmatch(n)
    if m:
        return [JCA_COMPOUND_HASHES[m.group("hash")]] if m.group("hash") in JCA_COMPOUND_HASHES else []
    return [JCA_NAMES[jca_name(n)]] if jca_name(n) in JCA_NAMES else []


def java_import_algorithm(name):
    """The algorithm an imported Java name belongs to, or None."""
    best = max((prefix for prefix in JAVA_IMPORTS if name.startswith(prefix)), key=len, default=None)
    return JAVA_IMPORTS[best] if best else None


class TreeSitterJava(TreeSitterGrammar):
    module, language_name, query_source = "tree_sitter_java", "Java", JAVA_TREE_SITTER_QUERY

    def scan(self, path):
        text = read_source(path)
        lines = text.splitlines()
        source = "\n".join(lines).encode("utf-8")
        captures = self.captures(self.parser.parse(source).root_node)
        findings = []

        def text(node):
            return source[node.start_byte:node.end_byte].decode("utf-8", "replace")

        def line_of(node):
            row = node.start_point[0]
            return row + 1, lines[row] if row < len(lines) else ""

        # Constants: a name declared once in the file with a string literal and
        # never assigned again, so getInstance(SIG) names what SIG holds.
        declared = defaultdict(list)
        for node in captures.get("declarator", ()):
            declared[text(node.child_by_field_name("name"))].append(text(node.child_by_field_name("value")))
        assigned = set()
        for node in captures.get("assignment", ()):
            left = node.child_by_field_name("left")
            if left is not None:
                field = left.child_by_field_name("field") if left.type == "field_access" else left
                assigned.add(text(field))
        declared_count = defaultdict(int)  # every declaration of a name, whatever its value
        for node in captures.get("declared", ()):
            declared_count[text(node)] += 1
        constants = {name: values[0][1:-1] for name, values in declared.items()
                     if len(values) == 1 and declared_count[name] == 1 and name not in assigned}
        int_constants = {}
        for node in captures.get("int_declarator", ()):
            name = text(node.child_by_field_name("name"))
            if declared_count[name] == 1 and name not in assigned:
                int_constants[name] = text(node.child_by_field_name("value"))

        def int_value(node):
            """The decimal value of an int literal or int constant, or None."""
            raw = text(node) if node.type == "decimal_integer_literal" else (
                int_constants.get(text(node)) if node.type == "identifier" else None)
            raw = raw.replace("_", "").rstrip("lL") if raw else None
            return str(int(raw)) if raw and raw.isdigit() else None

        def binding_of(call):
            """The variable a getInstance result is stored in, when that name is
            bound exactly once in the file, or None."""
            parent = call.parent
            if parent is not None and parent.type == "variable_declarator":
                name = text(parent.child_by_field_name("name"))
            elif parent is not None and parent.type == "assignment_expression":
                left = parent.child_by_field_name("left")
                left = left.child_by_field_name("field") if left.type == "field_access" else left
                name = text(left)
            else:
                return None
            bound = declared_count[name] + (name in assigned)
            return name if bound == 1 else None

        generators = {}  # binding -> (JCA class, findings of its getInstance call)

        call_names = set()  # literals passed straight to getInstance: call sites, not names
        for node in sorted(captures.get("call", ()), key=lambda n: n.start_byte):
            owner, arguments = node.child_by_field_name("object"), node.child_by_field_name("arguments")
            if owner is None or arguments is None or text(owner).rsplit(".", 1)[-1] not in JCA_CLASSES:
                continue
            first = next((c for c in arguments.named_children if c.type != "comment"), None)
            if first is None:
                continue
            call_names.add(first.start_byte)
            if first.type == "string_literal":
                name = text(first)[1:-1]
            elif first.type == "identifier" and text(first) in constants:
                name = constants[text(first)]
            else:
                continue  # a name only known at run time
            line, snippet = line_of(node)
            made = [Finding(algo, path, line, snippet) for algo in jca_algorithms(name)]
            findings += made
            cls = text(owner).rsplit(".", 1)[-1]
            binding = binding_of(node) if cls in JCA_INIT_METHODS else None
            if binding:
                generators[binding] = (cls, made)

        # Key sizes and curves: gen.initialize(2048), gen.initialize(new
        # RSAKeyGenParameterSpec(3072, F4)), gen.initialize(new
        # ECGenParameterSpec("secp384r1")), aesGen.init(256). Only literal
        # values and constants, through a generator bound once in the file; a
        # generator initialized with two different values claims neither.
        stated = defaultdict(set)
        for node in captures.get("init", ()):
            receiver, arguments = node.child_by_field_name("object"), node.child_by_field_name("arguments")
            if receiver is None or arguments is None:
                continue
            receiver = receiver.child_by_field_name("field") if receiver.type == "field_access" else receiver
            generator = generators.get(text(receiver))
            if generator is None or JCA_INIT_METHODS[generator[0]] != text(node.child_by_field_name("name")):
                continue
            first = next((c for c in arguments.named_children if c.type != "comment"), None)
            if first is None:
                continue
            value = None
            if first.type == "object_creation_expression":
                spec = text(first.child_by_field_name("type")).rsplit(".", 1)[-1]
                spec_args = first.child_by_field_name("arguments")
                spec_first = next((c for c in spec_args.named_children if c.type != "comment"), None) \
                    if spec_args is not None else None
                if spec_first is not None and spec in ("RSAKeyGenParameterSpec", "DSAGenParameterSpec"):
                    value = ("size", int_value(spec_first))
                elif spec_first is not None and spec == "ECGenParameterSpec":
                    curve = text(spec_first)[1:-1] if spec_first.type == "string_literal" else \
                        constants.get(text(spec_first)) if spec_first.type == "identifier" else None
                    value = ("curve", JCA_CURVES.get((curve or "").lower()))
            else:
                value = ("size", int_value(first))
            if value and value[1]:
                stated[text(receiver)].add(value)
        for binding, values in stated.items():
            if len(values) != 1:
                continue
            (kind, value), = values
            for f in generators[binding][1]:
                if (kind == "size" and f.algorithm in JCA_SIZE_ALGORITHMS) or (kind == "curve" and f.algorithm == "EC"):
                    f.params = value

        # Algorithm names held in string literals anywhere else: an enum of JWT
        # algorithms, a constant passed on to another class. They show the
        # algorithm is in use somewhere, not where, so they are counted apart.
        named = set()
        for node in sorted(captures.get("string", ()), key=lambda n: n.start_byte):
            if node.start_byte in call_names:
                continue
            line, snippet = line_of(node)
            for algo, params in jca_named(text(node)[1:-1]) or jose_named(text(node)[1:-1]):
                if (line, algo, params) not in named:
                    named.add((line, algo, params))
                    findings.append(Finding(algo, path, line, snippet, params, kind=NAME))

        for node in sorted(captures.get("import", ()), key=lambda n: n.start_byte):
            # A package wildcard (java.security.*) matches no class-level prefix,
            # so it names no algorithm; a class's static members do.
            names = [c for c in node.children if c.type in ("scoped_identifier", "identifier")]
            algo = java_import_algorithm(names[0].text.decode("utf-8", "replace")) if names else None
            if algo:
                row = node.start_point[0]
                findings.append(Finding(algo, path, row + 1, lines[row] if row < len(lines) else "", kind=IMPORT))

        # EC keys and imports take the file's usage when every signature or key
        # agreement call in it agrees, as in Python; otherwise they stay EC.
        usages = {f.algorithm for f in findings if f.kind == CALL and f.algorithm in ("ECDSA", "ECDH")}
        if len(usages) == 1:
            for f in findings:
                if f.algorithm == "EC":
                    f.algorithm = next(iter(usages))
        return findings


