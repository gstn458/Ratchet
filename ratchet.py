JAVA_TREE_SITTER_QUERY = """
(import_declaration) @import
(method_invocation name: (identifier) @method (#eq? @method "getInstance")) @call
(variable_declarator value: (string_literal)) @declarator
(assignment_expression) @assignment
"""

# JCA engine classes whose getInstance(name) names the algorithm.
JCA_CLASSES = {
    "KeyPairGenerator", "KeyFactory", "Signature", "Cipher", "KeyAgreement", "MessageDigest",
    "Mac", "KeyGenerator", "SecretKeyFactory", "AlgorithmParameterGenerator", "AlgorithmParameters",
}

# Standard JCA names (Java Security Standard Algorithm Names), lower-cased, as
# JCA matches them without regard to case. Only algorithms in the registry
# are mapped; anything else (SHA-512, EdDSA, XDH, Ed448, X448) records nothing.
JCA_NAMES = {
    "rsa": "RSA", "rsassa-pss": "RSA",
    "ec": "EC", "ecdsa": "ECDSA", "ecdh": "ECDH", "ecdhc": "ECDH",
    "dsa": "DSA", "dh": "DH", "diffiehellman": "DH",
    "ed25519": "Ed25519", "x25519": "X25519",
    "des": "DES", "desede": "3DES", "tripledes": "3DES",
    "rc4": "RC4", "arcfour": "RC4", "aes": "AES",
    "md5": "MD5", "sha1": "SHA-1", "sha-1": "SHA-1", "sha": "SHA-1",
    "sha256": "SHA-256", "sha-256": "SHA-256",
}
JCA_SIGNATURE = re.compile(r"(?P<hash>[a-z0-9/-]+?)with(?P<key>rsa|ecdsa|dsa)(?:andmgf1|/pss|inp1363format)?")
JCA_PREFIXED = re.compile(r"(?:hmac|pbkdf2withhmac)(?P<hash>.+)")
JCA_PBE = re.compile(r"pbewith(?P<hash>[a-z0-9-]+?)and(?P<cipher>.+)")
JCA_OAEP = re.compile(r"oaepwith(?P<hash>.+?)andmgf1padding")


def jca_name(name):
    """A name with a key or block size suffix (AES_256, RC4_128) removed."""
    return re.sub(r"_\d+$", "", name)


def jca_algorithms(name):
    """The registry algorithms a JCA algorithm name uses, one per primitive:
    SHA1withRSA is RSA and SHA-1, RSA/ECB/OAEPWithSHA-1AndMGF1Padding is RSA
    and SHA-1, PBEWithMD5AndDES is MD5 and DES. [] for a name it does not know."""
    n = name.strip().lower()
    m = JCA_SIGNATURE.fullmatch(n)
    if m:
        key = JCA_NAMES[m.group("key")]
        digest = JCA_NAMES.get(m.group("hash"))
        return [key] + ([digest] if digest else [])
    if "/" in n:  # Cipher transformation: algorithm/mode/padding
        cipher, _, rest = n.partition("/")
        found = [JCA_NAMES[jca_name(cipher)]] if jca_name(cipher) in JCA_NAMES else []
        oaep = JCA_OAEP.search(rest)
        if oaep and JCA_NAMES.get(oaep.group("hash")):
            found.append(JCA_NAMES[oaep.group("hash")])
        return found
    m = JCA_PBE.fullmatch(n)
    if m:
        digest = re.sub(r"^hmac", "", m.group("hash"))
        return [JCA_NAMES[x] for x in (digest, jca_name(m.group("cipher"))) if x in JCA_NAMES]
    m = JCA_PREFIXED.fullmatch(n)
    if m:
        return [JCA_NAMES[m.group("hash")]] if m.group("hash") in JCA_NAMES else []
    return [JCA_NAMES[jca_name(n)]] if jca_name(n) in JCA_NAMES else []


def java_import_algorithm(name):
    """The algorithm an imported Java name belongs to, or None."""
    best = max((prefix for prefix in JAVA_IMPORTS if name.startswith(prefix)), key=len, default=None)
    return JAVA_IMPORTS[best] if best else None


class TreeSitterJava(TreeSitterGrammar):
    module, language_name, query_source = "tree_sitter_java", "Java", JAVA_TREE_SITTER_QUERY

    def scan(self, path):
        text = read_source(path)
        lines = text.splitlines()
        source = "\n".join(lines).encode("utf-8")
        captures = self.captures(self.parser.parse(source).root_node)
        findings = []

        def text(node):
            return source[node.start_byte:node.end_byte].decode("utf-8", "replace")

        def line_of(node):
            row = node.start_point[0]
            return row + 1, lines[row] if row < len(lines) else ""

        # Constants: a name declared once in the file with a string literal and
        # never assigned again, so getInstance(SIG) names what SIG holds.
        declared = defaultdict(list)
        for node in captures.get("declarator", ()):
            declared[text(node.child_by_field_name("name"))].append(text(node.child_by_field_name("value")))
        assigned = set()
        for node in captures.get("assignment", ()):
            left = node.child_by_field_name("left")
            if left is not None:
                field = left.child_by_field_name("field") if left.type == "field_access" else left
                assigned.add(text(field))
        constants = {name: values[0][1:-1] for name, values in declared.items()
                     if len(values) == 1 and name not in assigned}

        for node in sorted(captures.get("call", ()), key=lambda n: n.start_byte):
            owner, arguments = node.child_by_field_name("object"), node.child_by_field_name("arguments")
            if owner is None or arguments is None or text(owner).rsplit(".", 1)[-1] not in JCA_CLASSES:
                continue
            first = next((c for c in arguments.named_children if c.type != "comment"), None)
            if first is None:
                continue
            if first.type == "string_literal":
                name = text(first)[1:-1]
            elif first.type == "identifier" and text(first) in constants:
                name = constants[text(first)]
            else:
                continue  # a name only known at run time
            line, snippet = line_of(node)
            for algo in jca_algorithms(name):
                findings.append(Finding(algo, path, line, snippet))

        for node in sorted(captures.get("import", ()), key=lambda n: n.start_byte):
            # A package wildcard (java.security.*) matches no class-level prefix,
            # so it names no algorithm; a class's static members do.
            names = [c for c in node.children if c.type in ("scoped_identifier", "identifier")]
            algo = java_import_algorithm(names[0].text.decode("utf-8", "replace")) if names else None
            if algo:
                row = node.start_point[0]
                findings.append(Finding(algo, path, row + 1, lines[row] if row < len(lines) else "", kind=IMPORT))

        # EC keys and imports take the file's usage when every signature or key
        # agreement call in it agrees, as in Python; otherwise they stay EC.
        usages = {f.algorithm for f in findings if f.kind == CALL and f.algorithm in ("ECDSA", "ECDH")}
        if len(usages) == 1:
            for f in findings:
                if f.algorithm == "EC":
                    f.algorithm = next(iter(usages))
        return findings


class GoFindings(list):
    """scan_go's findings, plus facts about the file that the package-level
    ECDSA/ECDH rule in walk() needs: whether it shows key agreement and
    whether it signs."""

    def __init__(self, findings=(), ecdh=False, signs=False):
        super().__init__(findings)
        self.ecdh = ecdh
        self.signs = signs
        self.in_test = False  # set by walk() from the path relative to the scan root


def go_package_ecdh(scanned):
    """Apply the ECDSA/ECDH rule to {directory: [GoFindings, ...]}."""
    for files in scanned.values():
        production_ecdh = any(f.ecdh and not f.in_test for f in files)
        for found in files:
            if found.signs:
                continue
            if found.ecdh or (production_ecdh and not found.in_test):
                for f in found:
                    if f.algorithm == "ECDSA":
                        f.algorithm = "EC"


def scan_go(path, lex=regex_go_lex):
    findings = []
    lines = read_source(path).splitlines()

    code, strings, import_lines = lex("\n".join(lines))
    # The names each import path is bound to in this file: its own package
    # name, an alias, "." for a dot import or "_" for a blank one.
    names = defaultdict(set)
    for paths in import_lines.values():
        for import_path, name in paths:
            names[import_path].add(name or import_path.rsplit("/", 1)[-1])
    imports = set(names)

    import_findings = defaultdict(list)  # import path -> its findings
    for idx, paths in sorted(import_lines.items()):
        for import_path, _ in paths:
            algo = GO_IMPORTS.get(import_path)
            if algo:
                findings.append(Finding(algo, path, idx + 1, lines[idx], kind=IMPORT))
                import_findings[import_path].append(findings[-1])
    variants = defaultdict(set)  # import path -> algorithms its calls used
    # Each call pattern is matched through the names its package is bound to,
    # so gorsa.GenerateKey counts when crypto/rsa is imported as gorsa, and a
    # different package that happens to be called rsa does not.
    calls = [(go_bind(pattern, import_path, name), algo, group)
             for import_path, pattern, algo, group in GO_CALL_PATTERNS
             for name in sorted(names.get(import_path, ())) if name != "_"]
    variant_calls = [(import_path, go_bind(pattern, import_path, name), algo)
                     for import_path, patterns in GO_VARIANT_CALLS.items()
                     for pattern, algo in patterns
                     for name in sorted(names.get(import_path, ())) if name != "_"]
    elliptic = GO_ELLIPTIC_IMPORT in imports
    elliptic_direct = [go_bind(GO_ELLIPTIC_DIRECT[0], GO_ELLIPTIC_IMPORT, name)
                       for name in sorted(names.get(GO_ELLIPTIC_IMPORT, ())) if name != "_"]
    elliptic_direct += GO_ELLIPTIC_DIRECT[1:]
    # Every rule's match contains a known substring, such as "rsa." for the
    # crypto/rsa calls. A line, or a whole file, without any of them cannot
    # match, so the regular expressions only run where one appears. This
    # changes no finding; it is the difference between scanning every line of
    # a large repository and scanning the few that mention a crypto package.
    # The names stand in for the package's own name; a dot import leaves calls
    # with no prefix to look for, so a file with one is matched line by line.
    bound = {name for import_path in GO_PACKAGE_TOKEN.keys() | GO_VARIANT_CALLS.keys() | {GO_ELLIPTIC_IMPORT}
             for name in names.get(import_path, ()) if name != "_"}
    tokens = {name + "." for name in bound}
    if elliptic:
        tokens.add("Scalar")
    gate = re.compile("" if "." in bound else "|".join(map(re.escape, sorted(tokens))))
    joined = "\n".join(code)
    if not gate.search(joined):
        code_lines = ()
    else:
        code_lines = enumerate(zip(lines, code), start=1)
    # Patterns run on code only, so calls in comments and strings never match.
    # The finding still shows the original line.
    for i, (line, text) in code_lines:
        if not gate.search(text):
            continue
        for pattern, algo, group in calls:
            m = pattern.search(text)
            if m:
                params = m.group(group) if group else None
                findings.append(Finding(algo, path, i, line, params))
        for import_path, pattern, algo in variant_calls:
            if pattern.search(text):
                variants[import_path].add(algo)
                findings.append(Finding(algo, path, i, line))
        if elliptic and any(p.search(text) for p in elliptic_direct):
            findings.append(Finding("EC", path, i, line))

    for import_path, used in variants.items():
        if len(used) == 1:
            for f in import_findings[import_path]:
                f.algorithm = next(iter(used))

    # The same reasoning: each check needs a substring its pattern contains.
    ecdh = ("ECDH" in joined or "ecdh." in joined) and any(
        GO_ECDH_NAME.search(GO_TLS_SUITE.sub("", text)) for text in code)
    ecdh = ecdh or (elliptic and "ScalarMult" in joined
                    and any(GO_SCALAR_MULT.search(text) for text in code))
    # ecdsa.Sign and friends through crypto/ecdsa's names (its own name when
    # it is not imported, as before), or .Sign( on any key.
    ecdsa_names = sorted(names.get("crypto/ecdsa") or {"ecdsa"})
    signing = [go_bind(GO_ECDSA_SIGNING, "crypto/ecdsa", name) for name in ecdsa_names if name != "_"]
    signs = (".Sign" in joined or "." in ecdsa_names or any(name + "." in joined for name in ecdsa_names)) \
        and any(p.search(text) for p in signing for text in code)
    return GoFindings(findings, ecdh=ecdh, signs=signs)


