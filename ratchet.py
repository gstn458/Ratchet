GO_LEX_SPECIAL = re.compile(r"[\n\"'`/]")
GO_LEX_QUOTED = {
    # A backslash escapes the next character, even a line break, and a quoted
    # literal otherwise ends at its closing quote or at the end of the line.
    '"': re.compile(r'(?:[^"\\\n]|\\[\s\S]?)*'),
    "'": re.compile(r"(?:[^'\\\n]|\\[\s\S]?)*"),
}


def go_lex(text):
    """Split Go source into code and string literals, line by line.

    Returns (code, strings): code[i] is line i with comments removed and every
    string or rune literal reduced to its empty quotes, and strings[i] lists
    the contents of the string literals that start on line i. This is not a Go
    parser. It is just enough to tell code from comments and strings, so
    nothing inside either is mistaken for an import or a call. It moves from
    one quote, slash or line break to the next rather than character by
    character, so plain code is copied in runs.
    """
    code, strings = [], []
    line_code, line_strings = [], []
    i, n = 0, len(text)

    def end_line():
        code.append("".join(line_code))
        strings.append(line_strings[:])
        line_code.clear()
        line_strings.clear()

    while i < n:
        m = GO_LEX_SPECIAL.search(text, i)
        if not m:
            line_code.append(text[i:])
            break
        j = m.start()
        if j > i:
            line_code.append(text[i:j])
        c = text[j]
        if c == "\n":
            end_line()
            i = j + 1
        elif c == "/" and text.startswith("//", j):
            k = text.find("\n", j)
            i = n if k < 0 else k
        elif c == "/" and text.startswith("/*", j):
            # A block comment leaves a space where it closes; its line breaks
            # still end lines.
            k = text.find("*/", j + 2)
            stop = n if k < 0 else k
            for _ in range(text.count("\n", j + 2, stop)):
                end_line()
            if k < 0:
                i = n
            else:
                line_code.append(" ")
                i = k + 2
        elif c == "/":
            line_code.append(c)
            i = j + 1
        elif c == "`":
            k = text.find("`", j + 1)
            stop = n if k < 0 else k
            raw = text[j + 1:stop]
            opened = len(code)
            for _ in range(raw.count("\n")):
                end_line()
            if k < 0:
                i = n
            else:
                line_code.append("``")
                # Attributed to the line the literal opens on.
                if opened == len(code):
                    line_strings.append(raw)
                else:
                    strings[opened].append(raw)
                i = k + 1
        else:
            e = GO_LEX_QUOTED[c].match(text, j + 1).end()
            if c == '"':
                line_strings.append(text[j + 1:e])
            line_code.append(c + c)
            i = e + 1
    end_line()
    return code, strings


GO_IMPORT_LINE = re.compile(r"^\s*import\b")


# An import's path, already reduced to empty quotes by go_lex, with the name
# it is bound to when the import gives one: gorsa "crypto/rsa", . "crypto/md5"
# or _ "crypto/sha1".
GO_IMPORT_SPEC = re.compile(r'(?:(?<![\w.])([A-Za-z_]\w*|\.)\s+)?(?:""|``)')


def go_imports(code, strings):
    """{line index: [(import path, name or None)]} for import declarations
    only. The name is the alias the import binds the package to, or None for
    the package's own name."""
    lines = {}
    in_group = False
    for idx, line in enumerate(code):
        if in_group:
            lines[idx] = strings[idx]
            if ")" in line:
                in_group = False
        elif GO_IMPORT_LINE.match(line):
            lines[idx] = strings[idx]
            after = line.split("import", 1)[1]
            if after.lstrip().startswith("(") and ")" not in after:
                in_group = True
    imports = {}
    for idx, paths in lines.items():
        if not paths:
            continue
        names = [name if name != "import" else None for name in GO_IMPORT_SPEC.findall(code[idx])]
        if len(names) != len(paths):
            names = [None] * len(paths)  # not a line this can pair up; use the packages' own names
        imports[idx] = list(zip(paths, names))
    return imports


