SUPPORTED_REGISTRY_SCHEMA = 2


class RegistryError(Exception):
    pass


def load_registry(script_dir=None):
    """Return (registry dict, source) where source is the file path or "embedded".

    A registry.json that exists but cannot be used is an error, never a silent
    fall back to the embedded copy: the scan would otherwise run on different
    claims than the user put in front of it.
    """
    script_dir = script_dir or os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(script_dir, "registry.json")
    if os.path.isfile(path):
        source = path
        try:
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
        except OSError as e:
            raise RegistryError(f"cannot read {path}: {e}")
    else:
        source, text = "embedded", _EMBEDDED_REGISTRY
    try:
        registry = json.loads(text)
    except ValueError as e:
        raise RegistryError(f"{source}: not valid JSON: {e}")
    version = registry.get("schema_version") if isinstance(registry, dict) else None
    if version != SUPPORTED_REGISTRY_SCHEMA:
        raise RegistryError(
            f"{source}: registry schema_version {version!r} is not supported "
            f"(this ratchet reads version {SUPPORTED_REGISTRY_SCHEMA})"
        )
    return registry, source


try:
    REGISTRY, REGISTRY_SOURCE = load_registry()
except RegistryError as e:
    sys.exit(f"ratchet: {e}")

ALGORITHMS = REGISTRY["algorithms"]


def parameter_claims(algo, params):
    """(oid, nistQuantumSecurityLevel) for an algorithm at a parameter set.

    A known parameter set listed in the registry overrides the entry's values;
    otherwise the entry's values apply. oid may be None: the registry records
    no OID where none identifies the algorithm without more information.
    """
    spec = ALGORITHMS[algo]
    override = spec.get("parameter_sets", {}).get(params or "", {})
    return (
        override.get("oid", spec["oid"]),
        override.get("nist_quantum_security_level", spec["nist_quantum_security_level"]),
    )


def registry_digest(registry):
    """SHA-256 of the registry's content, independent of formatting.

    Recorded in every CBOM next to registry_version, so a CBOM produced from a
    locally edited registry is distinguishable from one produced from the
    published registry of the same version.
    """
    text = json.dumps(registry, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


REGISTRY_DIGEST = registry_digest(REGISTRY)

